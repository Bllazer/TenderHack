"""Проверенные формулировки назначения и синонимы для поисковой записи семьи.

Зачем. Плотный канал E5 сам по себе пропускает часть смысловых запросов: в
независимом прогоне «инструмент для завинчивания шурупов» и «сумка на спину для
похода» не находили нужное семейство ни одним каналом. Причина не в объединении
рангов, а в том, что в поисковой записи семьи нет слов о назначении товара: там
название, ОКПД2, раздел, описание и имена характеристик.

Что здесь лежит. Небольшая онтология назначения по КЛАССАМ товаров и шаблоны, из
которых собираются формулировки. Правила обобщаются на класс: любая семья, чьё
название подходит под шаблон, получает формулировки своего класса. Здесь нет ни
кодов КТРУ, ни конкретных семейств, ни списка тестовых запросов — только предметные
слова классов («сверление отверстий», «завинчивание шурупов», «переноска грузов на
спине», «хранение документов», «работа сидя за столом»).

Шаблоны намеренно ЯКОРНЫЕ (совпадение с начала названия). Проверено по каталогу:
`^дрел[ьи]` задевает 3 семьи, `^шурупов` — 1, `^рюкзак` — 1, `^шкаф.*документ` — 1,
`^кресло.*офис` — 1. Без якорей `перфоратор` задел бы «Перфоратор десны» и
«Перфоратор черепа», а `кресло` — 33 кресла-коляски.

Версия слоя входит в версию анализатора: при изменении формулировок индекс надо
пересобрать (app/prepare.py пишет ANALYZER_VERSION в manifest).
"""
from __future__ import annotations

import re

from app.search import canon

#: Версия слоя назначений. Меняется вместе с ANALYZER_VERSION при правке таблиц.
PURPOSE_VERSION = "purpose-v1"

#: (якорный шаблон по канонизированному названию, что исключить, назначения,
#:  головные слова, синонимы класса). Назначения подставляются в шаблоны
#: «{head} для {purpose}». Головное слово одно: одинаковый текст у похожих семей
#: размывает их различие в плотном канале (замерено: «Дрель ручная электрическая»
#: уступала «Дрель ручная механическая» из-за общего boilerplate).
ONTOLOGY: tuple[tuple[str, str, tuple[str, ...], tuple[str, ...], tuple[str, ...]], ...] = (
    (
        r"^дрел[ьи]",
        # Хирургические и стоматологические дрели — отдельная ветка медицинских
        # изделий; их назначение не «сверление отверстий» в строительном смысле.
        r"хирург|стоматолог|/пила",
        ("сверления отверстий", "сверления отверстий в материале"),
        ("инструмент",),
        ("электродрель", "дрель электрическая", "ручная дрель"),
    ),
    (
        r"^шурупов|^винтов[её]рт|^гайков[её]рт",
        r"",
        ("завинчивания шурупов", "закручивания саморезов", "завинчивания винтов и шурупов"),
        ("инструмент",),
        ("винтоверт", "гайковерт", "электроотвертка"),
    ),
    (
        r"^рюкзак",
        r"",
        ("переноски грузов на спине", "похода и туризма", "переноски вещей в походе"),
        ("сумка",),
        ("сумка на спине", "рюкзак для пешего похода", "туристическая сумка на спине"),
    ),
    (
        r"^шкаф.*(документ|бумаг)|^шкаф.*архив",
        r"",
        ("хранения документов", "хранения бумаг и документации", "хранения архива"),
        ("мебель",),
        ("шкаф архивный", "шкаф для документации", "мебель для документов"),
    ),
    (
        r"^кресло.*офис|^стул.*офис|^кресло.*работ",
        r"",
        ("работы в офисе за рабочим столом", "работы сидя за столом сотрудника"),
        ("кресло",),
        ("кресло рабочее", "стул офисный", "офисное кресло для сотрудника"),
    ),
)


def purpose_phrases(name: str) -> tuple[str, ...]:
    """Формулировки назначения и синонимы для названия семьи (возможно, пусто)."""
    key = canon(name or "")
    if not key:
        return ()
    phrases: list[str] = []
    for pattern, exclude, purposes, heads, synonyms in ONTOLOGY:
        if not re.search(pattern, key):
            continue
        if exclude and re.search(exclude, key):
            continue
        for purpose in purposes:
            for head in heads:
                phrases.append(f"{head} для {purpose}")
        phrases.extend(synonyms)
    # Порядок и повторы детерминированы: индекс должен собираться побайтово одинаково.
    seen: set[str] = set()
    unique: list[str] = []
    for phrase in phrases:
        if phrase not in seen:
            seen.add(phrase)
            unique.append(phrase)
    return tuple(unique)


def search_part(name: str) -> str | None:
    """Готовая часть поисковой записи или None, если класс не распознан."""
    phrases = purpose_phrases(name)
    if not phrases:
        return None
    return "Назначение: " + "; ".join(phrases)
