import { expect, test } from '@playwright/test'
test('refresh restores description, unsent answer and CSV rows', async ({ page }) => {
 await page.goto('/')
 await page.getByLabel('Описание товара', { exact: true }).fill('Дрель; питание: от сети')
 await page.reload()
 await expect(page.getByLabel('Описание товара', { exact: true })).toHaveValue('Дрель; питание: от сети')
 await page.getByRole('button', { name: 'Подобрать КТРУ' }).click()
 await page.getByRole('radio', { name: 'Дрели электрические' }).check()
 await page.getByRole('button', { name: 'Продолжить' }).click()
 await page.getByRole('button', { name: 'Перейти: Уточнение' }).click()
 await page.getByLabel('Значение', { exact: true }).fill('650')
 await page.reload()
 await expect(page.getByLabel('Значение', { exact: true })).toHaveValue('650')
 await page.getByRole('button', { name: 'Загрузить CSV', exact: true }).click()
 await page.route('**/api/v1/analyses/csv', route => route.fulfill({ json: { rows: [{line:2,description:'Стол'}],notes:[],rows_skipped:[],truncated:false } }))
 await page.locator('input[type=file]').setInputFiles({name:'test.csv',mimeType:'text/csv',buffer:Buffer.from('описание\nСтол')})
 await page.getByLabel('Описание строки 2').fill('Стол; высота: 75 см')
 await page.reload()
 await expect(page.getByLabel('Описание строки 2')).toHaveValue('Стол; высота: 75 см')
 await page.getByRole('button', { name: 'Один товар', exact: true }).click()
 await page.getByRole('button', { name: 'Перейти: Уточнение' }).click()
})
