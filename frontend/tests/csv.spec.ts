import { expect, test } from '@playwright/test'
test('CSV preview, sequential analysis, row questions and saved return preserve manual mode', async ({ page }) => {
  await page.route('**/api/v1/analyses/csv', route => route.fulfill({ json: { rows: [{ line: 2, description: 'Дрель; питание: от сети' }, { line: 3, description: 'Стол; высота: 75 см' }], notes: [], rows_skipped: [], truncated: false } }))
  await page.goto('/')
  await page.getByLabel('Описание товара', { exact: true }).fill('Мой ручной товар')
  await page.getByRole('button', { name: 'Загрузить CSV', exact: true }).click()
  await page.locator('input[type=file]').setInputFiles({ name: 'товары.csv', mimeType: 'text/csv', buffer: Buffer.from('описание\nДрель\nСтол') })
  await expect(page.getByLabel('Описание строки 2')).toHaveValue('Дрель; питание: от сети')
  await page.getByRole('button', { name: 'Проверить товары' }).click()
  await expect(page.getByRole('button', { name: 'Уточнить' })).toHaveCount(2)
  await page.getByRole('button', { name: 'Уточнить' }).first().click()
  await page.getByRole('radio', { name: 'Дрели электрические' }).check()
  await page.getByRole('button', { name: 'Продолжить' }).click()
  await page.getByRole('button', { name: 'Перейти: Уточнение' }).click()
  await page.getByLabel('Значение', { exact: true }).fill('650')
  await page.getByRole('button', { name: 'Продолжить' }).click()
  await page.getByRole('button', { name: 'Подтвердить код' }).click()
  await expect(page.locator('.csv-table')).toContainText('Код подтверждён')
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.getByRole('button', { name: 'Копировать код строки 2' }).click()
  await expect(page.getByRole('button', { name: 'Копировать код строки 2' })).toHaveText('Скопировано')
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('TEST-DRILL-MAINS')
  await page.getByRole('button', { name: 'Посмотреть' }).click()
  await expect(page.getByRole('heading', { name: 'Подбор завершён' })).toBeVisible()
  await page.getByRole('button', { name: 'К списку товаров', exact: false }).click()
  await page.getByRole('button', { name: 'Один товар', exact: true }).click()
  await expect(page.getByLabel('Описание товара', { exact: true })).toHaveValue('Мой ручной товар')
})
