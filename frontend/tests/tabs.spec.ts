import { expect, test } from '@playwright/test'
test('tabs retain an unsent answer and editing description invalidates old result', async ({ page }) => {
 await page.goto('/')
 await page.getByLabel('Описание товара', { exact: true }).fill('Дрель; питание: от сети')
 await page.getByRole('button', { name: 'Подобрать КТРУ' }).click()
 await page.getByRole('radio', { name: 'Дрели электрические' }).check()
 await page.getByRole('button', { name: 'Продолжить' }).click()
 await page.getByRole('button', { name: 'Перейти: Уточнение' }).click()
 const value = page.getByLabel('Значение', { exact: true })
 await value.fill('650')
 await page.getByRole('button', { name: 'Перейти: Результат' }).click()
 await page.getByRole('button', { name: 'Перейти: Уточнение' }).click()
 await expect(value).toHaveValue('650')
 await page.getByRole('button', { name: 'Перейти: Описание' }).click()
 await expect(page.getByLabel('Описание товара', { exact: true })).toHaveValue('Дрель; питание: от сети')
 await page.getByRole('button', { name: 'Перейти: Уточнение' }).click()
 await expect(value).toHaveValue('650')
 await page.getByRole('button', { name: 'Перейти: Описание' }).click()
 await page.getByLabel('Описание товара', { exact: true }).fill('Новый товар')
 await expect(page.getByRole('button', { name: 'Перейти: Результат' })).toBeDisabled()
})
