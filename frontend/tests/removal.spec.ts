import { expect, test } from '@playwright/test'

test('single candidate remains on result, code can be copied before mandatory checks finish', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/')
  await page.getByLabel('Описание товара', { exact: true }).fill('Дрель; Питание: от сети')
  await page.getByRole('button', { name: 'Подобрать КТРУ' }).click()
  await page.getByRole('radio', { name: 'Дрели электрические' }).check()
  await page.getByRole('button', { name: 'Продолжить' }).click()
  await expect(page.getByRole('heading', { name: 'Проверьте результат' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Подтвердить код' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Скопировать код' }).click()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('TEST-DRILL-MAINS')
  await expect(page.getByRole('heading', { name: 'Проверьте результат' })).toBeVisible()
})

test('deleting an extracted fact survives refresh and does not restore it from description', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Описание товара', { exact: true }).fill('Дрель; Питание: от сети; Мощность: 650 Вт')
  await page.getByRole('button', { name: 'Подобрать КТРУ' }).click()
  await page.getByRole('radio', { name: 'Дрели электрические' }).check()
  await page.getByRole('button', { name: 'Продолжить' }).click()
  await expect(page.getByRole('button', { name: 'Подтвердить код' })).toBeVisible()
  await page.getByRole('button', { name: 'Удалить характеристику: Мощность', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Удалить характеристику: Мощность', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Подтвердить код' })).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Удалить характеристику: Мощность', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Уточнить характеристики' }).click()
  await page.getByLabel('Значение', { exact: true }).fill('700')
  await page.getByRole('button', { name: 'Продолжить' }).click()
  await expect(page.locator('.result-data')).toContainText('700')
  await expect(page.getByRole('button', { name: 'Подтвердить код' })).toBeVisible()
})
